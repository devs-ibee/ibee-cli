#!/usr/bin/env python3
"""Generate the CLI's commands from the public API contract (``contract/ibee-cloud.yaml``).

One command per contract operation, each making that operation's one SDK call and
printing the server's answer:

* path parameters are positional arguments, in path order;
* query parameters, headers and request-body fields are options named after the
  field (``ssh_key_ids`` -> ``--ssh-key-ids``); ``workspace_id`` is the global
  ``--workspace`` option and ``X-Idempotency-Key``/``Idempotency-Key`` is
  ``--idempotency-key`` (the SDK sends a random key when it is not given);
* booleans are ``--x/--no-x``, arrays of scalars repeat the option, and objects, arrays
  of objects and other shapes take JSON (``@FILE`` reads a file, ``@-`` stdin);
* required fields are required options; nothing else is checked before sending;
* destructive commands (every DELETE plus ``CONFIRM``) ask for confirmation unless
  ``--yes``.

The one convenience is the VM creates (``vms create``, ``gpus create``): besides
``--billing-catalog JSON`` they take ``--billing-interval HOURLY|MONTHLY``, which builds
``billing_catalog`` from the plan's entry in ``GET /compute/plans`` (see
``src/ibee_cli/billing_selection.py``).

Writes ``src/ibee_cli/commands/<group>.py``, ``src/ibee_cli/commands/__init__.py`` and
``COMMANDS.md``. Run it after changing the contract or this file:

    python scripts/generate_commands.py           # rewrite the generated files
    python scripts/generate_commands.py --check   # exit 1 when they are out of date
"""

