PY_TYPES = {"str": "str", "int": "int", "float": "float", "bool": "bool", "json": "str",
            "list[str]": "List[str]", "list[int]": "List[int]", "list[float]": "List[float]"}


def app_var(words: list) -> str:
    return "_".join(w.replace("-", "_") for w in words) + "_app" if words else "app"


def option_line(f: Field) -> str:
    py = PY_TYPES[f.kind]
    help_arg = f", help={f.help!r}" if f.help else ""
    if f.location == "path":
        metavar = f.name.upper()
        return f"    {f.var}: {py} = typer.Argument(..., metavar={metavar!r}, show_default=False{help_arg}),"
    decl = f"{f.option}/--no-{f.option[2:]}" if f.kind == "bool" else f.option
    metavar = ", metavar='JSON'" if f.kind == "json" else ""
    if f.required:
        return f"    {f.var}: {py} = typer.Option(..., {decl!r}{metavar}, show_default=False{help_arg}),"
    return f"    {f.var}: Optional[{py}] = typer.Option(None, {decl!r}{metavar}, show_default=False{help_arg}),"


def command_help(c: Command) -> str:
    parts = [c.summary + ("." if c.summary and not c.summary.endswith(".") else "")]
    if c.description and c.description != c.summary:
        parts.append(c.description)
    if c.vm_create:
        parts.append(
            "billing_catalog: pass --billing-catalog JSON, or --billing-interval HOURLY|MONTHLY to send the "
            "--plan-id plan's billing_catalog from GET /compute/plans with that billing_options entry merged in."
        )
    parts.append(f"API: {c.method} {c.path} ({c.operation_id}).")
    return "\n\n".join(parts)


def render_command(c: Command) -> str:
    lines = [
        f"@{app_var(c.words[:-1])}.command({c.words[-1]!r}, help={command_help(c)!r}, short_help={c.summary!r})",
        "@handle_api_errors",
        f"def {c.function}(",
        "    ctx: typer.Context,",
    ]
    for f in c.fields:
        lines.append(option_line(f))
        if c.vm_create and f.name == "billing_catalog":
            lines.append(
                "    billing_interval: Optional[str] = typer.Option(None, '--billing-interval', show_default=False, "
                "help='HOURLY or MONTHLY: send the --plan-id plan\\'s billing_catalog from GET /compute/plans with "
                "its billing_options entry for this interval merged in (instead of --billing-catalog).'),"
            )
    if c.confirm:
        lines.append("    yes: bool = typer.Option(False, '--yes', '-y', help='Do not ask for confirmation.'),")
    lines.append(") -> None:")
    path_args = [f for f in c.fields if f.location == "path"]
    if c.confirm:
        shown = ", ".join("{" + f.var + "}" for f in path_args)
        prompt = f"{c.summary} {shown}?" if shown else f"{c.summary}?"
        lines.append(f"    confirm(ctx, yes, f{prompt!r})")
    lines.append("    client = sdk(ctx)")
    # The global --workspace is every operation's workspace_id, sent explicitly (the SDK's
    # default does not reach its streaming downloads).
    kwargs = ["workspace_id=workspace(ctx)"]
    for f in c.fields:
        if f.location == "path":
            continue
        if c.vm_create and f.name == "billing_catalog":
            value = f"vm_billing_catalog(client, workspace(ctx), {c.vm_create!r}, plan_id, site_id, billing_catalog, billing_interval)"
        elif f.kind == "json":
            value = f"json_arg({f.var}, {f.option!r})"
        else:
            value = f.var
        kwargs.append(f"{f.kwarg}={value}")
    args = [f.var for f in path_args]
    args.append("**compact(" + ", ".join(kwargs) + ")")
    call = f"client.{c.resource}.{c.sdk_method}({', '.join(args)})"
    if len(call) > 100:
        inner = "".join(f"            {k},\n" for k in kwargs)
        positional = "".join(f"        {f.var},\n" for f in path_args)
        call = f"client.{c.resource}.{c.sdk_method}(\n{positional}        **compact(\n{inner}        ),\n    )"
    lines.append(f"    result = {call}")
    if c.binary:
        lines.append("    write_bytes(result)")
    else:
        extra = "".join(f", {name}={value!r}" for name, value in (("collection", c.collection), ("id_field", c.id_field)) if value)
        lines.append(f"    emit(result{extra})")
    return "\n".join(lines)


def render_module(module: str, cli: str, help_text: str, commands: list, info: dict) -> str:
    words_needed: list = []
    for c in commands:
        for i in range(1, len(c.words)):
            prefix = c.words[:i]
            if prefix not in words_needed:
                words_needed.append(prefix)
    uses = {
        "compact": True,
        "confirm": any(c.confirm for c in commands),
        "json_arg": any(f.kind == "json" and not (c.vm_create and f.name == "billing_catalog") for c in commands for f in c.fields),
        "sdk": True,
        "workspace": True,
        "write_bytes": any(c.binary for c in commands),
    }
    helpers = [name for name, used in uses.items() if used]
    render = ["emit", "handle_api_errors"] if any(not c.binary for c in commands) else ["handle_api_errors"]
    lines = [option_line(f) for c in commands for f in c.fields]
    typing_names = [n for n in ("List", "Optional") if any(n + "[" in line for line in lines)]
    if any(c.vm_create for c in commands) and "Optional" not in typing_names:
        typing_names.append("Optional")
    out = [HEADER.format(**info) + f'"""``ibee {cli}``: {help_text} (one command per contract operation)."""', ""]
    out += ["from __future__ import annotations", ""]
    if typing_names:
        out += [f"from typing import {', '.join(typing_names)}", ""]
    out += ["import typer", ""]
    if any(c.vm_create for c in commands):
        out.append("from ..billing_selection import vm_billing_catalog")
    out.append(f"from ..helpers import {', '.join(helpers)}")
    out.append(f"from ..render import {', '.join(render)}")
    out.append("")
    out.append(f"app = typer.Typer(help={help_text!r}, no_args_is_help=True)")
    for prefix in words_needed:
        key = " ".join([cli, *prefix])
        out.append(f"{app_var(prefix)} = typer.Typer(help={SUBGROUP_HELP[key]!r}, no_args_is_help=True)")
        out.append(f"{app_var(prefix[:-1])}.add_typer({app_var(prefix)}, name={prefix[-1]!r})")
    for c in commands:
        out.append("")
        out.append("")
        out.append(render_command(c))
    return "\n".join(out) + "\n"


def render_init(info: dict) -> str:
    lines = [HEADER.format(**info) + '"""The command groups, in `ibee --help` order."""', ""]
    lines.append("from . import " + ", ".join(sorted(module for module, _, _ in GROUPS)))
    lines.append("")
    lines.append("#: (CLI name, Typer app) of every command group.")
    lines.append("GROUPS = [")
    for module, cli, _ in GROUPS:
        lines.append(f"    ({cli!r}, {module}.app),")
    lines.append("]")
    return "\n".join(lines) + "\n"


def render_reference(commands: list, info: dict) -> str:
    lines = [
        "<!-- Generated by scripts/generate_commands.py from contract/ibee-cloud.yaml; do not edit. -->",
        "",
        "# Command reference",
        "",
        f"One `ibee` command per operation of the IBEE public API contract {info['version']} "
        f"({len(commands)} operations). Path parameters are arguments; every query parameter, header and "
        "request-body field is an option of the same name (`ssh_key_ids` is `--ssh-key-ids`). "
        "`ibee COMMAND --help` shows each option's description from the contract.",
        "",
    ]
    for module, cli, help_text in GROUPS:
        group = [c for c in commands if c.group == module]
        lines += [f"## `ibee {cli}`", "", help_text + ".", "", "| Command | Operation | API |", "| --- | --- | --- |"]
        for c in group:
            args = " ".join(f.name.upper() for f in c.fields if f.location == "path")
            extra = " (asks for confirmation; `--yes` skips it)" if c.confirm else ""
            lines.append(f"| `ibee {c.cli}{' ' + args if args else ''}`{extra} | `{c.operation_id}` | `{c.method} {c.path}` |")
        lines.append("")
    return "\n".join(lines)


def outputs() -> dict:
    contract = Contract(CONTRACT)
    info = {"title": contract.doc["info"]["title"], "version": contract.doc["info"]["version"]}
    commands = build(contract)
    files = {COMMANDS_DIR / "__init__.py": render_init(info), REFERENCE: render_reference(commands, info)}
    for module, cli, help_text in GROUPS:
        group = [c for c in commands if c.group == module]
        files[COMMANDS_DIR / f"{module}.py"] = render_module(module, cli, help_text, group, info)
    return files


def main(argv: list) -> int:
    check = "--check" in argv
    files = outputs()
    stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    generated = {COMMANDS_DIR / f"{module}.py" for module, _, _ in GROUPS} | {COMMANDS_DIR / "__init__.py"}
    extra = sorted(p for p in COMMANDS_DIR.glob("*.py") if p not in generated)
    if check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        for path in extra:
            print(f"not generated: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale or extra:
            print("Run: python scripts/generate_commands.py", file=sys.stderr)
            return 1
        print(f"The commands match {CONTRACT.relative_to(ROOT)}.")
        return 0
    for path in stale:
        path.write_text(files[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    for path in extra:
        path.unlink()
        print(f"removed {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
