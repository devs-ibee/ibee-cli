def snake(name: str) -> str:
    """Fern's Python names: ``revokeS3Credential`` -> ``revoke_s3credential``, ``Secret Store`` -> ``secret_store``."""
    name = re.sub(r"(?<=[a-z])(?=[A-Z])", "_", name)
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").lower()


class Contract:
    def __init__(self, path: pathlib.Path) -> None:
        self.raw = path.read_text(encoding="utf-8")
        self.doc = yaml.safe_load(self.raw)
        self.components = self.doc.get("components", {})

    def resolve(self, node: Any) -> Any:
        seen = 0
        while isinstance(node, dict) and "$ref" in node:
            _, _, kind, name = node["$ref"].split("/", 3)
            node = self.components[kind][name]
            seen += 1
            if seen > 50:  # pragma: no cover - a cyclic $ref
                raise ValueError("cyclic $ref")
        return node

    def properties(self, schema: Any) -> tuple[dict, set]:
        """An object schema's properties and required names, with ``allOf`` merged."""
        schema = self.resolve(schema) or {}
        props: dict = {}
        required: set = set()
        for part in schema.get("allOf", []):
            more, req = self.properties(part)
            props.update(more)
            required |= req
        props.update(schema.get("properties") or {})
        required |= set(schema.get("required") or [])
        return props, required

    def kind(self, schema: Any) -> str:
        """``str``, ``int``, ``float``, ``bool``, ``list[str|int|float]`` or ``json``."""
        schema = self.resolve(schema) or {}
        if "allOf" in schema and len(schema["allOf"]) == 1 and not schema.get("properties"):
            return self.kind(schema["allOf"][0])
        for key in ("oneOf", "anyOf"):
            if key in schema:
                options = [self.resolve(s) for s in schema[key]]
                options = [s for s in options if s.get("type") != "null"]
                return self.kind(options[0]) if len(options) == 1 else "json"
        kind = schema.get("type")
        if isinstance(kind, list):
            kinds = [k for k in kind if k != "null"]
            kind = kinds[0] if len(kinds) == 1 else None
        if kind == "array":
            item = self.kind(schema.get("items") or {})
            return f"list[{item}]" if item in ("str", "int", "float") else "json"
        return {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}.get(kind, "json")

    def enum(self, schema: Any) -> list:
        schema = self.resolve(schema) or {}
        if "allOf" in schema and len(schema["allOf"]) == 1:
            return self.enum(schema["allOf"][0])
        if schema.get("type") == "array":
            return self.enum(schema.get("items") or {})
        return [v for v in schema.get("enum") or [] if v is not None]

    def operations(self):
        for path, item in self.doc["paths"].items():
            shared = item.get("parameters", [])
            for method in HTTP_METHODS:
                if method in item:
                    yield path, method, item[method], shared


# ---------------------------------------------------------------------------
# The model of one command
# ---------------------------------------------------------------------------


@dataclass
class Field:
    name: str  # name in the contract
    location: str  # path, query, header or body
    kind: str
    required: bool
    help: str
    kwarg: str  # SDK keyword (path parameters are passed positionally)
    var: str  # Python parameter name in the generated function
    option: str  # --option (empty for path arguments)


@dataclass
class Command:
    operation_id: str
    method: str
    path: str
    summary: str
    description: str
    group: str  # module
    words: list  # CLI words after the group
    resource: str
    sdk_method: str
    fields: list = field(default_factory=list)
    confirm: bool = False
    binary: bool = False
    collection: Optional[str] = None
    id_field: Optional[str] = None
    vm_create: Optional[str] = None

    @property
    def function(self) -> str:
        return snake(self.operation_id)

    @property
    def cli(self) -> str:
        return " ".join([dict((m, c) for m, c, _ in GROUPS)[self.group], *self.words])


def clean(text: Optional[str]) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def field_help(contract: Contract, param_or_schema: dict, schema: Any) -> str:
    resolved = contract.resolve(schema) or {}
    text = clean(param_or_schema.get("description") or resolved.get("description"))
    values = contract.enum(schema)
    if values and not all(f"`{v}`" in text for v in values):
        text = (text + " " if text else "") + "One of: " + ", ".join(str(v) for v in values) + "."
    kind = contract.kind(schema)
    if kind == "json":
        text = (text + " " if text else "") + "JSON (@FILE reads a file, @- stdin)."
    return text


def list_id_field(contract: Contract, list_path: str, item_props: dict) -> Optional[str]:
    """The field of a listed item that ``-o id`` prints: the value the API takes for that
    item, i.e. the path parameter of ``GET <list path>/{param}`` (``bucket_name`` -> the
    item's ``name``). ``None`` leaves it to ``render.ID_FIELDS``."""
    pattern = re.compile(re.escape(list_path) + r"/\{([^}]+)\}")
    for path in contract.doc["paths"]:
        match = pattern.fullmatch(path)
        if not match or "get" not in contract.doc["paths"][path]:
            continue
        param = match.group(1)
        if param in item_props:
            return param
        if param.endswith("_name") and "name" in item_props:
            return "name"
        if "id" in item_props:
            return "id"
    return None


def python_name(name: str, taken: set) -> str:
    var = snake(name)
    if keyword.iskeyword(var) or var in RESERVED or var in taken:
        var += "_"
    taken.add(var)
    return var


def build(contract: Contract) -> list:
    group_of = {cli: module for module, cli, _ in GROUPS}
    commands = []
    seen = set()
    for path, method, op, shared in contract.operations():
        op_id = op["operationId"]
        if op_id not in COMMANDS:
            raise SystemExit(f"{op_id} ({method.upper()} {path}) has no command name in scripts/generate_commands.py")
        group_cli, *words = COMMANDS[op_id].split()
        tag = (op.get("tags") or [""])[0]
        command = Command(
            operation_id=op_id,
            method=method.upper(),
            path=path,
            summary=clean(op.get("summary")),
            description=clean(op.get("description")),
            group=group_of[group_cli],
            words=words,
            resource=snake(tag),
            sdk_method=snake(op_id),
            confirm=method == "delete" or op_id in CONFIRM,
            vm_create=VM_CREATES.get(op_id),
        )
        taken: set = set()
        headers: list = []  # after the body fields
        params = [contract.resolve(p) for p in shared + op.get("parameters", [])]
        path_order = re.findall(r"{([^}]+)}", path)
        params.sort(key=lambda p: (p["in"] != "path", path_order.index(p["name"]) if p["in"] == "path" else 0))
        for param in params:
            name, where = param["name"], param["in"]
            if name in GLOBAL_PARAMS:
                continue
            kwarg = HEADER_KWARGS.get(name.lower()) if where == "header" else snake(name)
            if kwarg is None:
                raise SystemExit(f"{op_id}: no SDK keyword known for header {name}")
            schema = param.get("schema") or {}
            (headers if where == "header" else command.fields).append(
                Field(
                    name=name, location=where, kind=contract.kind(schema),
                    # The SDK sends a random idempotency key when none is given.
                    required=bool(param.get("required")) and where != "header",
                    help=field_help(contract, param, schema), kwarg=kwarg, var=python_name(kwarg, taken),
                    option="" if where == "path" else "--" + kwarg.replace("_", "-"),
                )
            )
        body = op.get("requestBody")
        if body:
            content = body.get("content") or {}
            if list(content) != ["application/json"]:
                raise SystemExit(f"{op_id}: only JSON request bodies are supported ({list(content)})")
            props, required = contract.properties(content["application/json"].get("schema"))
            ordered = sorted(props.items(), key=lambda item: item[0] not in required)
            for name, schema in ordered:
                command.fields.append(
                    Field(
                        name=name, location="body", kind=contract.kind(schema),
                        required=name in required and not (command.vm_create and name == "billing_catalog"),
                        help=field_help(contract, schema, schema), kwarg=name, var=python_name(name, taken),
                        option="--" + name.replace("_", "-"),
                    )
                )
        command.fields += headers
        options = [f.option for f in command.fields if f.option]
        if len(options) != len(set(options)):
            raise SystemExit(f"{op_id}: two fields map to the same option: {options}")
        # Responses: a binary download, or the list a list operation wraps.
        for status, response in (op.get("responses") or {}).items():
            if not str(status).startswith("2"):
                continue
            content = (contract.resolve(response) or {}).get("content") or {}
            schemas = [contract.resolve(media.get("schema")) or {} for media in content.values()]
            if any(s.get("type") == "string" and s.get("format") == "binary" for s in schemas):
                command.binary = True
                continue
            schema = contract.resolve((content.get("application/json") or {}).get("schema"))
            if schema is not None and op_id.startswith("list"):
                item = schema.get("items") if schema.get("type") == "array" else None
                if item is None:
                    props, _ = contract.properties(schema)
                    arrays = [  # arrays of objects (not of strings such as site codes)
                        name for name, sub in props.items()
                        if (contract.resolve(sub) or {}).get("type") == "array"
                        and contract.properties(contract.resolve(sub).get("items") or {})[0]
                    ]
                    if len(arrays) == 1:
                        command.collection = arrays[0]
                        item = contract.resolve(props[arrays[0]]).get("items")
                if item is not None:
                    command.id_field = list_id_field(contract, path, contract.properties(item)[0])
        if command.cli in seen:
            raise SystemExit(f"two operations map to `ibee {command.cli}`")
        seen.add(command.cli)
        commands.append(command)
    missing = set(COMMANDS) - {c.operation_id for c in commands}
    if missing:
        raise SystemExit(f"command names for operations not in the contract: {sorted(missing)}")
    return commands


